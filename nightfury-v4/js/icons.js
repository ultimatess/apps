const cache = new Map();

export const ICON_NAMES = Object.keys(ART).filter((n) => n !== "heartSmall");

export const ICON_LABELS = {
  heart: "Heart", thumb: "Thumbs up", smile: "Smile", arrow: "Arrow", star: "Star", car: "Car",
  bolt: "Bolt", check: "Tick", cross: "Cross", note: "Music", warn: "Warning",
};

/** 1-bit bitmap of a named icon. `flip` mirrors it left-to-right (arrow -> left arrow). */
export function icon(name, { flip = false } = {}) {
  const key = `${name}|${flip}`;
  let bmp = cache.get(key);
  if (!bmp) {
    const rows = ART[name] ?? ART.cross;
    bmp = Bitmap.from2D(rows.map((r) => {
      const bits = [...r].map((c) => (c === "#" ? 1 : 0));
      return flip ? bits.reverse() : bits;
    }));
    cache.set(key, bmp);
  }
  return bmp;
}
