const GLYPHS = new Map(
  Object.entries(G).map(([ch, rows]) => [ch, Bitmap.from2D(rows.map((r) => [...r].map((c) => (c === "#" ? 1 : 0))))]),
);

export const GLYPH_HEIGHT = 7;

export function hasGlyph(ch) {
  return GLYPHS.has(ch.toUpperCase());
}

/** True if every character of `text` can be drawn with the pixel font. */
export function isPixelFontText(text) {
  const s = String(text ?? "");
  return s.length > 0 && [...s].every(hasGlyph);
}

export function glyph(ch) {
  return GLYPHS.get(ch.toUpperCase()) ?? GLYPHS.get("?");
}

export function measure(text, { scale = 1, spacing = 1 } = {}) {
  const chars = [...String(text)];
  if (!chars.length) return 0;
  const w = chars.reduce((sum, ch) => sum + glyph(ch).width * scale, 0);
  return w + (chars.length - 1) * spacing * scale;
}

/** Render text into a new bitmap exactly as wide as the text. */
export function renderText(text, { scale = 1, spacing = 1, height } = {}) {
  const w = Math.max(1, measure(text, { scale, spacing }));
  const h = height ?? GLYPH_HEIGHT * scale;
  const out = new Bitmap(w, h);
  drawText(out, text, 0, Math.floor((h - GLYPH_HEIGHT * scale) / 2), { scale, spacing });
  return out;
}

export function drawText(target, text, x, y, { scale = 1, spacing = 1 } = {}) {
  let cx = x;
  for (const ch of String(text)) {
    const g = glyph(ch);
    for (let gy = 0; gy < g.height; gy++) {
      for (let gx = 0; gx < g.width; gx++) {
        if (!g.data[gy * g.width + gx]) continue;
        for (let sy = 0; sy < scale; sy++) for (let sx = 0; sx < scale; sx++) target.set(cx + gx * scale + sx, y + gy * scale + sy);
      }
    }
    cx += (g.width + spacing) * scale;
  }
  return cx - x - spacing * scale;
}
